// Runs against an isolated schema in a transaction that is always rolled back.
import dotenv from "dotenv";
dotenv.config({ path: process.env.DOTENV_CONFIG_PATH ?? ".env.dev" });
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import pg from "pg";

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is required to run the OAuth trigger check");
}

const schema = "oauth_revocation_test";
const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();
try {
  await client.query("BEGIN");
  await client.query(`CREATE SCHEMA ${schema}`);
  await client.query(`CREATE TABLE ${schema}."OAuthClient" (
    id uuid PRIMARY KEY, "clientId" text NOT NULL, "clientSecret" text, "revocationEndpoint" text)`);
  await client.query(`CREATE TABLE ${schema}."OAuthAuthentication" (
    id uuid PRIMARY KEY, "oauthId" uuid NOT NULL REFERENCES ${schema}."OAuthClient" ON DELETE CASCADE,
    "accessToken" text NOT NULL, "refreshToken" text)`);
  await client.query(`CREATE TABLE ${schema}."OAuthRevocationSnapshot" (
    "authenticationId" uuid PRIMARY KEY, "oauthId" uuid NOT NULL, "clientId" text NOT NULL,
    "clientSecret" text, "revocationEndpoint" text)`);
  await client.query(`CREATE TABLE ${schema}."OAuthRevocationQueue" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "authenticationId" uuid NOT NULL,
    "clientId" text NOT NULL, "clientSecret" text, "revocationEndpoint" text,
    "accessToken" text NOT NULL, "refreshToken" text, attempts integer NOT NULL DEFAULT 0,
    "createdAt" timestamptz NOT NULL DEFAULT now(), "nextAttemptAt" timestamptz NOT NULL DEFAULT now())`);

  const triggers = await readFile(new URL("../migrations/002_oauth_revocation.sql", import.meta.url), "utf8");
  await client.query(triggers.replaceAll("aibot.", `${schema}.`));

  const clientId = "00000000-0000-0000-0000-000000000001";
  const authId = "00000000-0000-0000-0000-000000000002";
  await client.query(`INSERT INTO ${schema}."OAuthClient" VALUES ($1, $2, $3, $4)`, [clientId, "old", "secret", "https://example.com/revoke"]);
  await client.query(`INSERT INTO ${schema}."OAuthAuthentication" VALUES ($1, $2, $3, $4)`, [authId, clientId, "access", "refresh"]);
  await client.query(`UPDATE ${schema}."OAuthClient" SET "clientId" = $1 WHERE id = $2`, ["updated", clientId]);
  await client.query("SAVEPOINT before_delete");
  await client.query(`DELETE FROM ${schema}."OAuthClient" WHERE id = $1`, [clientId]);
  let result = await client.query(`SELECT * FROM ${schema}."OAuthRevocationQueue"`);
  assert.equal(result.rows.length, 1);
  assert.equal(result.rows[0].clientId, "updated");
  assert.equal(result.rows[0].accessToken, "access");
  assert.equal(result.rows[0].refreshToken, "refresh");
  await client.query("ROLLBACK TO SAVEPOINT before_delete");
  result = await client.query(`SELECT * FROM ${schema}."OAuthRevocationQueue"`);
  assert.equal(result.rows.length, 0);

  await client.query(`DELETE FROM ${schema}."OAuthAuthentication" WHERE id = $1`, [authId]);
  result = await client.query(`SELECT * FROM ${schema}."OAuthRevocationQueue"`);
  assert.equal(result.rows.length, 1);
  result = await client.query(`SELECT * FROM ${schema}."OAuthRevocationSnapshot"`);
  assert.equal(result.rows.length, 0);
  await client.query(`INSERT INTO ${schema}."OAuthAuthentication" VALUES ($1, $2, $3, $4)`, [authId, clientId, "new-access", null]);
  await client.query(`DELETE FROM ${schema}."OAuthClient" WHERE id = $1`, [clientId]);
  result = await client.query(`SELECT * FROM ${schema}."OAuthRevocationQueue" ORDER BY id`);
  assert.equal(result.rows.length, 2);
  assert.equal(result.rows[1].accessToken, "new-access");
  await client.query(`UPDATE ${schema}."OAuthRevocationQueue" SET attempts = attempts + 1,
    "nextAttemptAt" = now() + make_interval(secs => LEAST(86400, 60 * power(2, LEAST(attempts, 10)))::double precision)
    WHERE id = $1`, [result.rows[1].id]);
  console.log("OAuth revocation trigger integration checks passed.");
} finally {
  await client.query("ROLLBACK");
  await client.end();
}
